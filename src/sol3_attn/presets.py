def get_preset(profile: str) -> dict:
    """Return an independent copy of the model's kernel config and host policy.

    Pass kernel_config to sol3_attn_with_route. The host applies the stage,
    dense-step and block policy and supplies the actual token layout.
    """
    if profile not in _PRESETS:
        raise ValueError(f"Unknown Sol3 profile {profile!r}. Choose from {', '.join(_PRESETS)}.")
    return deepcopy(_PRESETS[profile])
